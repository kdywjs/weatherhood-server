create table weather_region (
 id varchar(128) primary key, name varchar(255) not null, supported boolean not null,
 nx integer, ny integer, pm10_station varchar(255), pm25_station varchar(255),
 check ((nx is null and ny is null) or (nx between 1 and 149 and ny between 1 and 253))
);
create table weather_value (
 id bigint generated by default as identity primary key,
 source varchar(255) not null, location varchar(255) not null, field varchar(255) not null,
 target timestamptz not null, issued timestamptz not null, collected timestamptz not null, payload text not null,
 unique(source, location, field, target)
);
create index weather_value_lookup on weather_value(location, target);
create table weather_collection (
 id varchar(512) primary key, next_attempt timestamptz not null, last_success timestamptz, last_attempt timestamptz not null
);
